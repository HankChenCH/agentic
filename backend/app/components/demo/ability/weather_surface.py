_WEEKDAYS = "一二三四五六日"


def _condition_icon(condition: str) -> str:
    if condition and condition in _CONDITION_ICONS:
        return _CONDITION_ICONS[condition]
    for prefix, path in _CONDITION_ICONS.items():
        if condition.startswith(prefix):
            return path
    return _ICON_PARTLY_CLOUDY


def _format_date(date: str) -> str:
    """ISO 日期 → 「9月5日 · 周六」；解析失败原样返回。"""
    try:
        d = datetime.strptime(date, "%Y-%m-%d")
    except (ValueError, TypeError):
        return date
    return f"{d.month}月{d.day}日 · 周{_WEEKDAYS[d.weekday()]}"


def build_weather_surface(weather: dict) -> list[dict[str, Any]]:
    """结构化天气数据 → A2UI 消息数组（createSurface + updateComponents）。"""
    surface_id = f"weather-{uuid.uuid4().hex}"
    components = [
        card(ROOT_COMPONENT_ID, "body"),
        column("body", ["header", "main", "sep", "humidity"]),
        # 标题行：左信息块 + 右单色天气图标
        row("header", ["head-left", "glyph"], align="start", justify="spaceBetween"),
        column("head-left", ["city", "date"]),
        text("city", weather.get("city", ""), variant="h4"),
        text("date", _format_date(weather.get("date", "")), variant="caption"),
        icon("glyph", _condition_icon(weather.get("condition", ""))),
        # 主行：大号温度 + 天气现象（宿主样式按基线对齐）
        row("main", ["temperature", "condition"], align="end"),
        text("temperature", f"{weather.get('temperature', '')}°", variant="h2"),
        text("condition", weather.get("condition", ""), variant="body"),
        # 尾段：发丝分隔线 + 弱化元信息
        divider("sep"),
        text("humidity", f"湿度 {weather.get('humidity', '')}%", variant="caption"),
    ]
    return render_surface(surface_id, components)
